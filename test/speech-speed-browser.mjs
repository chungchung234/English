import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
export async function testSpeechSpeed(page){
 const emit=event=>page.evaluate(event=>window.testPeer.dc.onmessage({data:JSON.stringify(event)}),event);
 const count=()=>page.evaluate(()=>window.testMessages.filter(m=>m.session?.audio?.output?.speed!==undefined).length);
 const choose=async value=>page.locator(`[name="speech-speed"][value="${value}"]`).check();
 await mkdir('test-results',{recursive:true});
 await page.locator('#speed-call').click();
 assert.equal(await page.getByRole('radio',{checked:true}).inputValue(),'0.85');
 await page.locator('#speed-dialog').screenshot({path:'test-results/speed-sheet-default.png'});
 assert.equal(await page.locator('#speed-range, #speed-reset, #speed-value').count(),0);
 await page.getByRole('radio',{checked:true}).focus();
 await page.keyboard.press('ArrowLeft');assert.equal(await page.getByRole('radio',{checked:true}).inputValue(),'0.7');
 await page.keyboard.press('ArrowRight');assert.equal(await page.getByRole('radio',{checked:true}).inputValue(),'0.85');
 await choose('1');await page.keyboard.press('Escape');assert.equal(await count(),0,'draft/cancel must not change audio');
 await page.locator('#speed-call').click();assert.equal(await page.getByRole('radio',{checked:true}).inputValue(),'0.85','cancel discards the draft');
 await page.keyboard.press('Escape');
 await emit({type:'response.created'});await emit({type:'output_audio_buffer.started'});
 await page.locator('#speed-call').click();await choose('1');await page.locator('#speed-apply').click();
 assert.equal(await count(),0);assert.equal(await page.locator('#speed-current').textContent(),'0.85×');
 assert.equal(await page.locator('#speed-pending').isVisible(),true);
 await emit({type:'response.done',response:{status:'completed'}});assert.equal(await count(),0,'wait for playback, not only model generation');
 await emit({type:'output_audio_buffer.stopped'});
 await page.waitForFunction(()=>document.querySelector('#speed-current').textContent==='1.0×');
 assert.equal(await count(),1);assert.equal(await page.locator('#speed-pending').isVisible(),false);
 assert.equal(await page.evaluate(()=>localStorage.getItem('loop.speech-speed:https://test-project.supabase.co|aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa')),'1');
 await page.screenshot({path:'test-results/speed-call.png'});
 await page.locator('#speed-call').click();await page.screenshot({path:'test-results/speed-sheet.png'});
 await page.setViewportSize({width:320,height:568});
 assert(await page.locator('#speed-apply').evaluate(n=>{const r=n.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight;}));
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'test-results/speed-sheet-compact.png'});await page.setViewportSize({width:390,height:844});
 await choose('0.7');await page.evaluate(()=>window.failNextSpeed=true);await page.locator('#speed-apply').click();
 await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('속도를 변경하지 못했어요'));
 assert.equal(await page.locator('#speed-current').textContent(),'1.0×');
 await page.locator('#speed-call').click();await choose('0.7');await page.locator('#speed-apply').click();
 await page.waitForFunction(()=>document.querySelector('#speed-current').textContent==='0.7×');
 // Older saved custom speeds remain truthful until the user chooses a preset.
 await emit({type:'session.updated',session:{audio:{output:{speed:1.15}}}});
 await page.locator('#speed-call').click();
 assert.equal(await page.getByRole('radio',{checked:true}).count(),0);
 assert.match(await page.locator('#speed-custom-current').textContent(),/1.15×/);
 assert.equal(await page.locator('#speed-apply').isDisabled(),true);
 await page.keyboard.press('Escape');assert.equal(await page.locator('#speed-current').textContent(),'1.15×');
 await page.locator('#speed-call').click();await choose('0.7');await page.locator('#speed-apply').click();
 await page.waitForFunction(()=>document.querySelector('#speed-current').textContent==='0.7×');
 await emit({type:'response.created'});await emit({type:'output_audio_buffer.started'});
 console.log('PASS: three speed options, native radio keyboard selection, cancel, deferred playback-safe update, acknowledged persistence, settings failure/retry and compact sheet.');
}
